"""Markdown + self-contained PDF exports using upstream Markdown validation."""
import html
import re
import markdown
from pathlib import Path
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image, KeepTogether
from scripts.utils.markdown import add_frontmatter, validate_markdown_structure

CSS = '''body{font:17px/1.65 system-ui;color:#223345;background:#f5f7fa;margin:0}
main{max-width:900px;margin:36px auto;padding:40px;background:white;border-radius:12px}
h1,h2,h3{line-height:1.3;color:#183f59}h2{margin-top:32px}img{max-width:100%;border:1px solid #d9e2e8;border-radius:8px}
pre{white-space:pre-wrap;overflow-wrap:anywhere}a{color:#176183}.meta{font-size:14px;background:#edf5fa;padding:16px}
li{margin:10px 0}footer{margin-top:36px;color:#687681;font-size:13px}'''


def guide_body(guide, manifest=None, captures=None):
    captures = captures or []
    text = '# ' + guide['title'] + '\n\n' + guide.get('summary', '') + '\n\n'
    if manifest:
        text += '**Deployment:** ' + manifest['label'] + '. ' + manifest['platform'] + '.\n\n'
        if manifest.get('synthetic'):
            text += '> Synthetic test fixture. These screenshots demonstrate the pipeline, not an installed Media Nexus client.\n\n'
        if manifest.get('config'):
            text += '## Deployment configuration\n\n'
            text += '\n'.join('- ' + key + ': ' + str(value) for key, value in sorted(manifest['config'].items())) + '\n\n'
    sections = ('prerequisites', 'steps', 'expected', 'recovery')
    labels = {'prerequisites': 'Prerequisites', 'steps': 'Steps', 'expected': 'Expected result', 'recovery': 'Recovery'}
    overrides = manifest.get('overrides', {}).get(guide['id'], {}) if manifest else {}
    for section in sections:
        text += '## ' + labels[section] + '\n\n'
        if section == 'steps':
            for index, step in enumerate(guide['steps'], 1):
                text += '### ' + str(index) + '. ' + step['title'] + '\n\n' + step['instruction'] + '\n\n'
                text += '**Expected:** ' + step['expected'] + '\n\n'
                if captures:
                    text += '![' + step['expected'] + '](screenshots/' + captures[index-1]['file'] + ')\n\n'
        else:
            value = guide.get(section) or ['Recovery guidance is not source-supported. Request review before giving recovery instructions.']
            text += '\n'.join('- ' + line for line in value) + '\n\n'
        if section in overrides:
            text += '### Deployment instruction\n\n' + overrides[section] + '\n\n'
    if 'notes' in overrides:
        text += '## Deployment notes\n\n' + overrides['notes'] + '\n\n'
    text += '## Evidence and review\n\n'
    text += '- Screenshot verification: ' + ('all documented fixture steps asserted in a fresh browser session.' if captures else 'not captured; running product behavior requires review.') + '\n'
    for item in guide['evidence']:
        text += '- Source: `' + item['path'] + ':' + str(item['line']) + '`; file SHA-256 `' + item['sha256'] + '`.\n'
    for note in guide.get('review', []):
        text += '- Review required: ' + note + '\n'
    text += '\nGenerated by Vaultline Docs. GPL-3.0-or-later. See package NOTICE, LICENSE and COPYING.\n'
    valid, issues = validate_markdown_structure(text)
    if not valid:
        raise ValueError('Invalid guide structure: ' + ', '.join(issues))
    return text


def write_guide(destination, guide, metadata, manifest=None, captures=None):
    body = guide_body(guide, manifest, captures)
    destination.mkdir(parents=True, exist_ok=True)
    name = guide['id']
    (destination / (name + '.md')).write_text(add_frontmatter(body, metadata))
    # Escape all raw HTML before Markdown conversion; generated previews execute no scripts.
    rendered = markdown.markdown(html.escape(body), extensions=['extra'])
    meta = '<div class="meta">' + '<br>'.join(html.escape(k + ': ' + str(v)) for k,v in metadata.items()) + '</div>'
    page = '<!doctype html><html lang="en"><meta charset="utf-8"><title>' + html.escape(guide['title']) + '</title><style>' + CSS + '</style><main>' + meta + rendered + '</main></html>'
    (destination / (name + '.html')).write_text(page)
    return body


def pdf(destination, guide, metadata, body):
    styles = getSampleStyleSheet()
    styles['Normal'].fontSize = 10
    styles['Normal'].leading = 15
    styles['Normal'].spaceAfter = 8
    flow = [Paragraph('Vaultline Docs | DRAFT - review before publication', styles['Normal'])]
    for key in ('product', 'deployment', 'deployment_version', 'source_product_version', 'source_revision', 'generated_at', 'platform', 'capture_status'):
        if key in metadata:
            flow.append(Paragraph(html.escape(key + ': ' + str(metadata[key])), styles['Normal']))
    group = None
    def flush():
        nonlocal group
        if group:
            flow.append(KeepTogether(group))
        group = None
    for line in body.splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r'!\[([^\]]*)\]\((screenshots/[a-z0-9-]+\.png)\)', line)
        if match:
            path = destination / match.group(2)
            image = Image(str(path))
            ratio = min(480 / image.imageWidth, 300 / image.imageHeight)
            image.drawWidth = image.imageWidth * ratio
            image.drawHeight = image.imageHeight * ratio
            (group if group is not None else flow).extend([Spacer(1, 8), image, Paragraph(html.escape(match.group(1)), styles['Normal']), Spacer(1, 10)])
            continue
        style = styles['Normal']
        if line.startswith('# '):
            flush()
            style, line = styles['Title'], line[2:]
        elif line.startswith('## '):
            flush()
            style, line = styles['Heading2'], line[3:]
        elif line.startswith('### '):
            flush()
            group = []
            style, line = styles['Heading3'], line[4:]
        else:
            line = line.removeprefix('- ').removeprefix('> ')
        # Reportlab core fonts are ASCII; avoid unrenderable glyphs.
        line = line.replace('—', '-').replace('…', '...').replace('→', ' > ').replace('·', '|').replace('’', "'")
        line = re.sub(r'\*\*|`', '', line)
        (group if group is not None else flow).append(Paragraph(html.escape(line), style))
    flush()
    def footer(canvas, doc):
        canvas.setFillColor(colors.HexColor('#526879'))
        canvas.setFont('Helvetica', 8)
        canvas.drawString(42, 25, 'Vaultline Docs | Draft | ' + str(doc.page))
    SimpleDocTemplate(str(destination / (guide['id'] + '.pdf')), pagesize=A4,
                      rightMargin=42, leftMargin=42, topMargin=36, bottomMargin=40).build(flow, onFirstPage=footer, onLaterPages=footer)
